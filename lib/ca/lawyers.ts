//
// HOW EACH ENTRY WAS VERIFIED
//  1. Name, role, office address, practice areas and bio come from the
//     firm's own website (profileUrl), read on the date in `verification`.
//     practiceAreaSlugs are the FIRM's areas; primaryPracticeArea is the
//     lawyer's own. A firm that only does commercial real estate is not
//     given "property" unless the listed lawyer practises real estate.
//  2. yearsExperience is only set when the firm publishes the lawyer's
//     call-to-the-bar year (counted to 2026). Otherwise null + "Not published".
//  3. The site owner searched each lawyer on the provincial law society's
//     public directory (registerUrl) and confirmed the entry before it was
//     added. `registerChecked` records the date. Anyone not confirmed is
//     left out — see CHANGES.md for who was dropped and why.
//  4. No ratings or reviews. No virtual or appointment-only offices.
//
// IDs are "<city>-<province>-<name>" (toronto-on-…, london-on-…) so they can
// never match a UK or Irish id. scripts/check-ids.mjs fails the build check
// if any id is used twice across the three countries.
//
// These firms have NOT consented to being listed. The /ca/listings page
// gives them a removal route. People move firms — re-check now and then.
// ============================================================================

import type { StaticLawyer } from "@/lib/data/static-lawyers";
import { getCaProvince, type CaProvinceCode } from "@/lib/ca/provinces";

export interface CaLawyer extends StaticLawyer {
  province: CaProvinceCode;
  /** What was read on the firm's own website (not shown on the site). */
  verification: string;
  /** Date the site owner confirmed this lawyer on the law society directory. */
  registerChecked: string;
}

type CaEntry = Omit<CaLawyer, "regulator" | "sraNumber" | "registerUrl" | "province" | "registerChecked">;

function forProvince(code: CaProvinceCode, registerChecked: string) {
  const province = getCaProvince(code);
  return (entry: CaEntry): CaLawyer => ({
    regulator: province.regulator,
    sraNumber: null,
    registerUrl: province.directoryUrl,
    province: code,
    registerChecked,
    ...entry,
  });
}

